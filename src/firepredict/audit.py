"""Data-quality audit of the raw Var data. Writes results/audit/data_audit.md.

Rerun it after each download: the checks below are the evidence behind the
label rules in dataset.py (minimum fire size, unreliable years).

Usage:
    uv run python -m firepredict.audit
"""

import tempfile
import zipfile
from pathlib import Path

import geopandas as gpd
import pandas as pd

from firepredict.dataset import RAW_DIR, ROOT, START, load_bdiff, load_meteo

OUT = ROOT / "results" / "audit" / "data_audit.md"

SIZE_BINS = [0, 0.01, 0.1, 1, 10, float("inf")]
SIZE_LABELS = ["<100 m²", "100 m²–0.1 ha", "0.1–1 ha", "1–10 ha", "≥10 ha"]


def fires_by_size(fires: pd.DataFrame) -> pd.DataFrame:
    size = pd.cut(fires.area_ha, SIZE_BINS, labels=SIZE_LABELS, right=False)
    return pd.crosstab(fires.alert_time.dt.year.rename("year"), size)


def fire_days_by_threshold(fires: pd.DataFrame) -> pd.DataFrame:
    day = fires.alert_time.dt.normalize()
    out = {}
    for ha, name in [(0, "all"), (0.01, "≥100 m²"), (0.1, "≥0.1 ha"), (1, "≥1 ha")]:
        keep = fires.area_ha >= ha
        out[name] = day[keep].groupby(day[keep].dt.year).nunique()
    return pd.DataFrame(out).fillna(0).astype(int).T


def quality_flags(fires: pd.DataFrame) -> pd.DataFrame:
    year = fires.alert_time.dt.year.rename("year")
    return pd.DataFrame(
        {
            "fires": year.value_counts().sort_index(),
            "flag 'partielles ou non valides'": fires.quality_flag.notna().groupby(year).sum(),
            "area precision filled (new form)": fires.area_precision.notna().groupby(year).sum(),
        }
    )


def load_perimeters() -> pd.DataFrame:
    """DDTM 83 perimeters (date, polygon area in ha). Schemas differ by year."""
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for z in sorted((RAW_DIR / "ddtm83").glob("*.zip")):
            zipfile.ZipFile(z).extractall(Path(tmp) / z.stem)
        for shp in Path(tmp).rglob("*.shp"):
            g = gpd.read_file(shp)
            date_col = next((c for c in g.columns if c.upper() in ("DATE_ECLOS", "O_DATE_D")), None)
            if date_col is None:  # 1953-2002 file has only the year
                continue
            rows.append(
                pd.DataFrame(
                    {
                        "date": pd.to_datetime(g[date_col], errors="coerce"),
                        "area_ha": g.to_crs(2154).area / 1e4,
                    }
                )
            )
    # The same perimeter can appear in a yearly file and in a multi-year file.
    return pd.concat(rows).drop_duplicates().dropna()


def perimeter_check(fires: pd.DataFrame, perims: pd.DataFrame) -> tuple[str, pd.DataFrame]:
    """Do large fires appear in both sources (same date ± 1 day)?"""
    last = perims.date.max()
    fires = fires.assign(date=fires.alert_time.dt.normalize())
    fires = fires[fires.date <= last]
    perims = perims[perims.date >= START]

    def found(dates, other):
        return dates.apply(lambda d: ((other - d).abs() <= pd.Timedelta(days=1)).any())

    big_p = perims[perims.area_ha >= 10]
    big_f = fires[fires.area_ha >= 10]
    in_bdiff = found(big_p.date, fires.date)
    in_ddtm = found(big_f.date, perims.date)
    text = (
        f"Perimeters cover {START[:4]}–{last.year} (some years have no file).\n\n"
        f"- DDTM perimeters ≥10 ha found in BDIFF: {in_bdiff.sum()}/{len(big_p)}\n"
        f"- BDIFF fires ≥10 ha found in DDTM: {in_ddtm.sum()}/{len(big_f)}\n"
    )
    yearly = pd.DataFrame(
        {
            "BDIFF ha": fires.groupby(fires.date.dt.year).area_ha.sum(),
            "DDTM ha": perims.groupby(perims.date.dt.year).area_ha.sum(),
        }
    ).round(0)
    return text, yearly


def weather_coverage(meteo: pd.DataFrame) -> pd.DataFrame:
    """Stations reporting each variable, per year."""
    year = meteo.date.dt.year
    return pd.DataFrame(
        {v: meteo[meteo[v].notna()].groupby(year).NUM_POSTE.nunique() for v in ["TX", "RR", "FFM", "UN"]}
    ).T


def main() -> None:
    fires = load_bdiff()
    meteo = load_meteo()
    check_text, yearly_area = perimeter_check(fires, load_perimeters())

    sections = [
        "# Data audit: Var (83)",
        f"Generated by `python -m firepredict.audit` on {pd.Timestamp.now():%Y-%m-%d}.",
        "## BDIFF: fires per year by size",
        "A jump in tiny fires from 2023 points to a change in how fires are recorded, not more fire.",
        fires_by_size(fires).to_markdown(),
        "## BDIFF: fire days per year by minimum fire size",
        "Fire days are what the models predict. The main target uses ≥0.1 ha.",
        fire_days_by_threshold(fires).to_markdown(),
        "## BDIFF: data-quality fields per year",
        quality_flags(fires).fillna(0).astype(int).to_markdown(),
        "## BDIFF vs DDTM 83 perimeters",
        check_text,
        yearly_area.to_markdown(),
        "## Météo-France: stations reporting per year",
        "Suspect values (quality code 9) are removed before counting.",
        weather_coverage(meteo).to_markdown(),
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n\n".join(sections) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
